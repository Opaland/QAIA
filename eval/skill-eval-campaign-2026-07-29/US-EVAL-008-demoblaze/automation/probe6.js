const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto('https://www.demoblaze.com/prod.html?idp_=1');
  let priceText = await page.locator('.price-container').innerText().catch(()=>'?');
  console.log('product 1 price:', priceText);
  page.once('dialog', async d => { await d.accept(); });
  await page.locator('a[onclick^="addToCart"]').first().click();
  await page.waitForTimeout(1500);
  await page.goto('https://www.demoblaze.com/prod.html?idp_=2');
  let priceText2 = await page.locator('.price-container').innerText().catch(()=>'?');
  console.log('product 2 price:', priceText2);
  page.once('dialog', async d => { await d.accept(); });
  await page.locator('a[onclick^="addToCart"]').first().click();
  await page.waitForTimeout(1500);
  await page.goto('https://www.demoblaze.com/cart.html');
  await page.waitForTimeout(3000);
  console.log('totalp:', await page.locator('#totalp').innerText().catch(()=>'ERR'));
  const rows = await page.locator('#tbodyid tr').count();
  console.log('rows:', rows);
  await browser.close();
})();
