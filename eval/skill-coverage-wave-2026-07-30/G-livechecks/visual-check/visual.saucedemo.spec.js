// visual-check skill exercise against SauceDemo (docs/DEMO-TARGETS.md: Visual = OK).
// Steps follow plugins/qaia-playwright/skills/visual-check/SKILL.md:
//  1. one snapshot test per key screen, navigated to a stable state
//  2. first run creates baselines (NOT a pass)
//  3. snapshot scoped to a stable container, dynamic areas masked
//  4. @QAIA-VIS-<NNN> tags
const { test, expect } = require('@playwright/test');

const TOL = 0.01; // maxDiffPixelRatio

// Deliberate, verifiable regression used to PROVE the diff detects a real change.
// Enabled only with INJECT_REGRESSION=1 so baselines stay untouched.
async function maybeInjectRegression(page) {
  if (!process.env.INJECT_REGRESSION) return;
  await page.addStyleTag({
    content: `
      .btn_primary, #login-button, .btn_inventory { background-color: #b21f1f !important; }
      .inventory_item_name { color: #b21f1f !important; }
      .footer_robot { opacity: 0.25 !important; }
    `,
  });
}

async function login(page) {
  await page.goto('/');
  await page.locator('#user-name').fill('standard_user');
  await page.locator('#password').fill('secret_sauce');
  await page.locator('#login-button').click();
  await expect(page.locator('.title')).toHaveText('Products');
}

test('@QAIA-VIS-001 login screen container is visually stable', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('#login_button_container')).toBeVisible();
  await maybeInjectRegression(page);
  await expect(page.locator('.login_wrapper')).toHaveScreenshot('login-screen.png', {
    maxDiffPixelRatio: TOL,
  });
});

test('@QAIA-VIS-002 inventory list is visually stable', async ({ page }) => {
  await login(page);
  // Stable state: SauceDemo catalogue is static (6 fixed items), sort reset to default A-Z.
  await page.locator('[data-test="product-sort-container"]').selectOption('az');
  await maybeInjectRegression(page);
  await expect(page.locator('.inventory_list')).toHaveScreenshot('inventory-list.png', {
    maxDiffPixelRatio: TOL,
  });
});

test('@QAIA-VIS-003 footer (dynamic year masked) is visually stable', async ({ page }) => {
  await login(page);
  await maybeInjectRegression(page);
  // Guardrail #40: the footer copyright year is generated by JS (`new Date().getFullYear()`),
  // i.e. genuinely dynamic content -> mask it instead of relying on the tolerance budget.
  await expect(page.locator('footer.footer')).toHaveScreenshot('footer.png', {
    maxDiffPixelRatio: TOL,
    mask: [page.locator('footer.footer .footer_copy')],
  });
});
