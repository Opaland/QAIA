// gen-dataset-map.js — emits dataset-map.md (SKILL.md step 9) FROM the dataset, so the
// coverage matrix can never drift from the data it describes. Pure node, zero deps.
// Run: node gen-dataset-map.js
const fs = require('fs');
const path = require('path');
const d = JSON.parse(fs.readFileSync(path.join(__dirname, 'US-EVAL-008-dataset.json'), 'utf8'));

const esc = (s) => String(s).replace(/\|/g, '\\|');
const rows = d.cases.map((c) => {
  const outcome = c.expectedResult.status === '[open]'
    ? '`[open]` — fork exposed, not resolved'
    : `${c.expectedResult.status} — ${c.expectedResult.rule}`;
  const data = [c.shopperRef, c.cartRef, c.orderFormRef].filter(Boolean).join(', ');
  return `| ${c.id} | ${c.coversAC.join(', ')} | ${c.coversCondition} | ${c.coversScenario || '— (P3-deferred, no scenario)'} | ${data} | ${esc(outcome)} | ${c.assumptionRefs.join(', ') || '—'} |`;
});

const acCount = {};
for (const c of d.cases) for (const ac of c.coversAC) acCount[ac] = (acCount[ac] || 0) + 1;

const out = `# dataset-map — ${d._meta.usId}

Coverage matrix of \`${d._meta.usId}-dataset.json\`, one row per \`cases[]\` entry
(dataset-generate SKILL.md step 9). **Generated by \`gen-dataset-map.js\` — do not hand-edit**;
regenerate after any change to the dataset.

Source of truth for the conditions and scenario ids cited below:
- \`eval/skill-eval-campaign-2026-07-29/US-EVAL-008-demoblaze/state/03-design.md\` (conditions)
- \`eval/skill-eval-campaign-2026-07-29/US-EVAL-008-demoblaze/testbooks/cart-checkout.feature\` (scenario tags)

| Case | AC(s) | Condition | Test-book scenario | Data rows used | Expected outcome | Assumptions |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Coverage roll-up

| AC | cases |
|---|---|
${Object.keys(acCount).sort().map((ac) => `| ${ac} | ${acCount[ac]} |`).join('\n')}

- Cases: **${d.cases.length}** — of which **${d.cases.filter((c) => c.expectedResult.status === '[open]').length}** deliberately \`[open]\` (C-011, C-020).
- Entity rows: shoppers ${d.shoppers.length}, products ${d.products.length}, cart items ${d.cartItems.length}, carts ${d.carts.length}, order forms ${d.orderForms.length}.
- Design conditions covered: **${new Set(d.cases.map((c) => c.coversCondition)).size}/${new Set((fs.readFileSync(path.join(__dirname, '..', '..', 'skill-eval-campaign-2026-07-29', 'US-EVAL-008-demoblaze', 'state', '03-design.md'), 'utf8').match(/AC\\d-C\\d/g) || [])).size}**.
- Test-book scenarios with a backing data row: **${new Set(d.cases.map((c) => c.coversScenario).filter(Boolean)).size}/10**.

## Assumptions

${d._meta.assumptions.map((a) => `- **${a.id}** (${a.about}) — ${a.text}`).join('\n\n')}

## Verification

\`node verify-dataset.js\` — 20 checks over the properties the SKILL.md promises (see
\`verify-dataset.out.txt\`). \`node mutation-control.js\` — negative control, 18 injected
violations, all detected (\`mutation-control.out.txt\`).
`;
fs.writeFileSync(path.join(__dirname, 'dataset-map.md'), out);
console.log(`wrote dataset-map.md (${rows.length} rows)`);
